function getCurrentLanguage() {
    const languageFromUrl = new URLSearchParams(window.location.search).get("lang");
    if (languageFromUrl && Object.prototype.hasOwnProperty.call(storeTranslations, languageFromUrl)) {
        localStorage.setItem("brickStoreLang", languageFromUrl);
        return languageFromUrl;
    }

    const savedLang = localStorage.getItem("brickStoreLang");
    return Object.prototype.hasOwnProperty.call(storeTranslations, savedLang) ? savedLang : "en";
}

function applyGlobalLanguage() {
    const savedLang = getCurrentLanguage();
    const texts = { ...storeTranslations[savedLang], ...aboutTranslations[savedLang], ...libraryTranslations[savedLang], ...backgroundTranslations[savedLang], ...homeTranslations[savedLang], ...advancedSettingsTranslations[savedLang] };

    if (savedLang === "ar") {
        document.documentElement.setAttribute("dir", "rtl");
    } else {
        document.documentElement.setAttribute("dir", "ltr");
    }
    document.documentElement.setAttribute("lang", savedLang);

    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.getAttribute("data-i18n");
        if (Object.prototype.hasOwnProperty.call(texts, key)) {
            element.textContent = texts[key];
        }
    });

    document.querySelectorAll("[data-i18n-attr]").forEach(element => {
        element.getAttribute("data-i18n-attr").split(",").forEach(attributeMapping => {
            const [attribute, key] = attributeMapping.trim().split(":");
            if (attribute && key && Object.prototype.hasOwnProperty.call(texts, key)) {
                element.setAttribute(attribute, texts[key]);
            }
        });
    });

    if (document.body.dataset.pageTitle && Object.prototype.hasOwnProperty.call(texts, document.body.dataset.pageTitle)) {
        document.title = texts[document.body.dataset.pageTitle];
    }

    if (window.location.protocol === "file:") {
        document.querySelectorAll(".nav-menu a[href]").forEach(link => {
            const targetUrl = new URL(link.getAttribute("href"), window.location.href);
            targetUrl.searchParams.set("lang", savedLang);
            link.href = targetUrl.href;
        });
    }
}

function translate(key) {
    const lang = getCurrentLanguage();
    const texts = { ...storeTranslations[lang], ...aboutTranslations[lang], ...libraryTranslations[lang], ...backgroundTranslations[lang], ...homeTranslations[lang], ...advancedSettingsTranslations[lang] };
    return Object.prototype.hasOwnProperty.call(texts, key) ? texts[key] : key;
}

